-- WARNING: this script drops and recreates all application tables.
-- Run it only against a new database or after taking a backup.
DROP TABLE IF EXISTS enrollments;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS students;

CREATE TABLE students (
  student_id INTEGER PRIMARY KEY CHECK (student_id > 0),
  student_name VARCHAR(120) NOT NULL CHECK (length(trim(student_name)) > 0),
  age INTEGER NOT NULL CHECK (age BETWEEN 15 AND 100),
  email VARCHAR(255) NOT NULL UNIQUE CHECK (position('@' IN email) > 1),
  phone_number VARCHAR(25) NOT NULL,
  department VARCHAR(100) NOT NULL CHECK (length(trim(department)) > 0),
  student_year INTEGER NOT NULL CHECK (student_year BETWEEN 1 AND 8),
  admission_date DATE NOT NULL DEFAULT CURRENT_DATE,
  marks NUMERIC(5,2) NOT NULL CHECK (marks BETWEEN 0 AND 100),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','GRADUATED'))
);

CREATE TABLE courses (
  course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_name VARCHAR(120) NOT NULL UNIQUE CHECK (length(trim(course_name)) > 0),
  department VARCHAR(100) NOT NULL,
  credits INTEGER NOT NULL CHECK (credits BETWEEN 1 AND 10)
);

CREATE TABLE enrollments (
  enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
  enrollment_date DATE NOT NULL DEFAULT CURRENT_DATE,
  enrollment_status VARCHAR(20) NOT NULL DEFAULT 'ENROLLED' CHECK (enrollment_status IN ('ENROLLED','COMPLETED','DROPPED')),
  CONSTRAINT uq_student_course UNIQUE (student_id, course_id)
);

CREATE INDEX idx_students_department ON students(department);
CREATE INDEX idx_students_year ON students(student_year);
CREATE INDEX idx_enrollments_course ON enrollments(course_id);
